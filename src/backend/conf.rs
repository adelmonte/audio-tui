//! Generates PipeWire / WirePlumber drop-in files from audio-tui's config.
//!
//! Every file is named `60-audio-tui-<topic>.conf`, starts with a header
//! saying it's generated, and is removed again when the corresponding config
//! section goes back to defaults. audio-tui never edits any other file.
//!
//! Format: SPA-JSON (PipeWire's relaxed JSON: `key = value`, no commas
//! needed). We always quote strings, so arbitrary names are safe.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::config::{Config, Virtual, VirtualKind};

// ---------------------------------------------------------------- SPA-JSON

#[derive(Clone, Debug, PartialEq)]
pub enum J {
    Obj(Vec<(String, J)>),
    Arr(Vec<J>),
    Str(String),
    Int(i64),
    Float(f64),
    Bool(bool),
    /// Unquoted bare word (module/factory names, enum-like values).
    Bare(String),
}

pub fn obj(pairs: Vec<(&str, J)>) -> J {
    J::Obj(pairs.into_iter().map(|(k, v)| (k.to_string(), v)).collect())
}
pub fn s(v: &str) -> J {
    J::Str(v.to_string())
}
pub fn bare(v: &str) -> J {
    J::Bare(v.to_string())
}

fn key(k: &str) -> String {
    if !k.is_empty() && k.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-')) {
        k.to_string()
    } else {
        quote(k)
    }
}

fn quote(v: &str) -> String {
    let mut o = String::from("\"");
    for c in v.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

impl J {
    fn inline(&self) -> bool {
        match self {
            J::Obj(v) => v.len() <= 3 && v.iter().all(|(_, x)| !matches!(x, J::Obj(_) | J::Arr(_))),
            J::Arr(v) => v.iter().all(|x| !matches!(x, J::Obj(_) | J::Arr(_))),
            _ => true,
        }
    }

    pub fn write(&self, out: &mut String, indent: usize) {
        let pad = "    ".repeat(indent);
        let pad_in = "    ".repeat(indent + 1);
        match self {
            J::Str(v) => out.push_str(&quote(v)),
            J::Bare(v) => out.push_str(v),
            J::Int(n) => {
                let _ = write!(out, "{n}");
            }
            J::Float(f) => {
                // Values often come from f32 config fields: round away the noise.
                let f = &((f * 10_000.0).round() / 10_000.0);
                if f.fract() == 0.0 {
                    let _ = write!(out, "{f:.1}");
                } else {
                    let _ = write!(out, "{f}");
                }
            }
            J::Bool(b) => out.push_str(if *b { "true" } else { "false" }),
            J::Arr(v) if self.inline() => {
                out.push_str("[ ");
                for x in v {
                    x.write(out, indent);
                    out.push(' ');
                }
                out.push(']');
            }
            J::Arr(v) => {
                out.push_str("[\n");
                for x in v {
                    out.push_str(&pad_in);
                    x.write(out, indent + 1);
                    out.push('\n');
                }
                out.push_str(&pad);
                out.push(']');
            }
            J::Obj(v) if self.inline() => {
                out.push_str("{ ");
                for (k, x) in v {
                    out.push_str(&key(k));
                    out.push_str(" = ");
                    x.write(out, indent);
                    out.push(' ');
                }
                out.push('}');
            }
            J::Obj(v) => {
                out.push_str("{\n");
                for (k, x) in v {
                    out.push_str(&pad_in);
                    out.push_str(&key(k));
                    out.push_str(" = ");
                    x.write(out, indent + 1);
                    out.push('\n');
                }
                out.push_str(&pad);
                out.push('}');
            }
        }
    }
}

/// Render top-level sections (`section = value` pairs) as a file.
fn render(header: &str, sections: Vec<(&str, J)>) -> String {
    let mut out = String::new();
    out.push_str("# Generated by audio-tui. Edit ~/.config/audio-tui/config.toml instead;\n");
    out.push_str("# this file is rewritten (or deleted) when you apply changes there.\n");
    for l in header.lines() {
        out.push_str("# ");
        out.push_str(l);
        out.push('\n');
    }
    out.push('\n');
    for (name, v) in sections {
        out.push_str(&key(name));
        out.push_str(" = ");
        v.write(&mut out, 0);
        out.push_str("\n\n");
    }
    out
}

// ---------------------------------------------------------------- targets

#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Service {
    PipeWire,
    PipeWirePulse,
    WirePlumber,
    /// client.conf: picked up by apps when they next start.
    Clients,
}

impl Service {
    pub fn unit(self) -> Option<&'static str> {
        match self {
            Service::PipeWire => Some("pipewire.service"),
            Service::PipeWirePulse => Some("pipewire-pulse.service"),
            Service::WirePlumber => Some("wireplumber.service"),
            Service::Clients => None,
        }
    }
}

#[derive(Clone, Debug, PartialEq)]
pub struct DropIn {
    pub path: PathBuf,
    /// None = this file should not exist.
    pub content: Option<String>,
    pub service: Service,
    pub topic: &'static str,
}

pub struct Dirs {
    pub pipewire: PathBuf,
    pub pulse: PathBuf,
    pub client: PathBuf,
    pub wireplumber: PathBuf,
}

impl Dirs {
    pub fn user() -> Self {
        let base = dirs::config_dir().unwrap_or_else(|| PathBuf::from(".config"));
        Self {
            pipewire: base.join("pipewire/pipewire.conf.d"),
            pulse: base.join("pipewire/pipewire-pulse.conf.d"),
            client: base.join("pipewire/client.conf.d"),
            wireplumber: base.join("wireplumber/wireplumber.conf.d"),
        }
    }
    #[cfg(test)]
    pub fn under(root: &Path) -> Self {
        Self { pipewire: root.join("pw"), pulse: root.join("pulse"), client: root.join("client"), wireplumber: root.join("wp") }
    }
}

const PREFIX: &str = "60-audio-tui-";

fn file(dir: &Path, topic: &str) -> PathBuf {
    dir.join(format!("{PREFIX}{topic}.conf"))
}


fn device_rules(cfg: &Config) -> Option<String> {
    let mut alsa = Vec::new();
    let mut bluez = Vec::new();
    for (name, r) in &cfg.devices {
        let is_card = name.starts_with("alsa_card.") || name.starts_with("bluez_card.");
        let (match_key, pfx) = if is_card { ("device.name", "device") } else { ("node.name", "node") };
        let mut props = Vec::new();
        if let Some(d) = r.description.as_deref().filter(|d| !d.is_empty()) {
            props.push((format!("{pfx}.description"), s(d)));
            if !is_card {
                props.push(("node.nick".to_string(), s(d)));
            }
        }
        if let Some(true) = r.disabled {
            props.push((format!("{pfx}.disabled"), J::Bool(true)));
        }
        if let (Some(p), false) = (r.priority, is_card) {
            props.push(("priority.session".into(), J::Int(p)));
            props.push(("priority.driver".into(), J::Int(p)));
        }
        if props.is_empty() {
            continue;
        }
        let rule = obj(vec![
            ("matches", J::Arr(vec![obj(vec![(match_key, s(name))])])),
            ("actions", obj(vec![("update-props", J::Obj(props))])),
        ]);
        if name.starts_with("bluez_") {
            bluez.push(rule);
        } else {
            alsa.push(rule);
        }
    }
    if alsa.is_empty() && bluez.is_empty() {
        return None;
    }
    let mut sections = Vec::new();
    if !alsa.is_empty() {
        sections.push(("monitor.alsa.rules", J::Arr(alsa)));
    }
    if !bluez.is_empty() {
        sections.push(("monitor.bluez.rules", J::Arr(bluez)));
    }
    Some(render("Device names, disabled devices and priorities ([devices]).", sections))
}

/// Apps on `[privacy] allowlist` are remembered whatever the switches say.
/// WirePlumber's global settings override every per-stream rule, so when
/// there are exceptions, "off" is expressed as rules instead: every stream
/// gets `state.restore-* = false`, then the listed apps get it back.
fn exceptions(cfg: &Config) -> Vec<&str> {
    cfg.privacy.allowlist.iter().map(|a| a.trim()).filter(|a| !a.is_empty()).collect()
}

/// Rules that mark streams as "don't remember" except listed apps, in the
/// shape shared by WirePlumber `stream.rules`, pipewire-pulse `pulse.rules`
/// and client `stream.rules`.
fn privacy_stream_rules(cfg: &Config) -> Option<Vec<J>> {
    let (props, target) = cfg.privacy.remembers();
    let apps = exceptions(cfg);
    if (props && target) || apps.is_empty() {
        return None;
    }
    let mut off = Vec::new();
    if !props {
        off.push(("state.restore-props", J::Bool(false)));
    }
    if !target {
        off.push(("state.restore-target", J::Bool(false)));
    }
    let on = obj(vec![("update-props", obj(vec![("state.restore-props", J::Bool(true)), ("state.restore-target", J::Bool(true))]))]);
    let matches: Vec<J> = apps.iter().flat_map(|a| [obj(vec![("application.name", s(a))]), obj(vec![("application.process.binary", s(a))])]).collect();
    Some(vec![
        obj(vec![
            ("matches", J::Arr(vec![obj(vec![("media.class", s("~Stream/.*"))])])),
            ("actions", obj(vec![("update-props", obj(off))])),
        ]),
        obj(vec![("matches", J::Arr(matches)), ("actions", on)]),
    ])
}

fn privacy_wireplumber(cfg: &Config) -> Option<String> {
    let mut sections = Vec::new();
    if let Some(rules) = privacy_stream_rules(cfg) {
        sections.push(("stream.rules", J::Arr(rules)));
    } else {
        let (props, target) = cfg.privacy.remembers();
        if !props || !target {
            sections.push((
                "wireplumber.settings",
                obj(vec![("node.stream.restore-props", J::Bool(props)), ("node.stream.restore-target", J::Bool(target))]),
            ));
        }
    }
    if sections.is_empty() {
        return None;
    }
    Some(render("What WirePlumber may remember about apps ([privacy]).", sections))
}

fn routing_rules(cfg: &Config) -> Vec<J> {
    cfg.routing
        .iter()
        .filter(|r| !r.app.is_empty() && !r.target.is_empty())
        .map(|r| {
            obj(vec![
                ("matches", J::Arr(vec![obj(vec![("application.name", s(&r.app))]), obj(vec![("application.process.binary", s(&r.app))])])),
                ("actions", obj(vec![("update-props", obj(vec![("target.object", s(&r.target))]))])),
            ])
        })
        .collect()
}

/// pipewire-pulse (most desktop apps) and native clients get the same rules.
/// Privacy rules live only in WirePlumber's drop-in, which is what reads them.
fn client_rules(cfg: &Config, section: &str) -> Option<String> {
    let rules = routing_rules(cfg);
    if rules.is_empty() {
        return None;
    }
    Some(render("Per-app routing rules ([[routing]]).", vec![(section, J::Arr(rules))]))
}

fn clock(cfg: &Config) -> Option<String> {
    let c = &cfg.clock;
    let mut props = Vec::new();
    if c.rate > 0 {
        props.push(("default.clock.rate", J::Int(c.rate as i64)));
    }
    if !c.allowed_rates.is_empty() {
        props.push(("default.clock.allowed-rates", J::Arr(c.allowed_rates.iter().map(|r| J::Int(*r as i64)).collect())));
    }
    if c.quantum > 0 {
        props.push(("default.clock.quantum", J::Int(c.quantum as i64)));
    }
    if c.min_quantum > 0 {
        props.push(("default.clock.min-quantum", J::Int(c.min_quantum as i64)));
    }
    if c.max_quantum > 0 {
        props.push(("default.clock.max-quantum", J::Int(c.max_quantum as i64)));
    }
    if props.is_empty() {
        return None;
    }
    Some(render("Sample rate and buffer size ([clock]).", vec![("context.properties", obj(props))]))
}

fn positions(ch: u32) -> J {
    let p: &[&str] = match ch {
        1 => &["MONO"],
        6 => &["FL", "FR", "FC", "LFE", "RL", "RR"],
        _ => &["FL", "FR"],
    };
    J::Arr(p.iter().map(|x| bare(x)).collect())
}

fn desc(v: &Virtual) -> String {
    if v.description.is_empty() { v.name.clone() } else { v.description.clone() }
}

fn virtual_module(v: &Virtual) -> Result<(Option<J>, Option<J>), String> {
    let d = desc(v);
    let need = |x: &str, what: &str| if x.is_empty() { Err(format!("virtual “{}”: {what} is required", v.name)) } else { Ok(()) };
    Ok(match v.kind {
        VirtualKind::NullSink => (
            Some(obj(vec![
                ("factory", bare("adapter")),
                (
                    "args",
                    obj(vec![
                        ("factory.name", bare("support.null-audio-sink")),
                        ("node.name", s(&v.name)),
                        ("node.description", s(&d)),
                        ("media.class", bare("Audio/Sink")),
                        ("audio.position", positions(v.channels)),
                        ("monitor.channel-volumes", J::Bool(true)),
                        ("object.linger", J::Bool(true)),
                    ]),
                ),
            ])),
            None,
        ),
        VirtualKind::Combine => {
            if v.targets.is_empty() {
                return Err(format!("virtual “{}”: targets = [...] is required", v.name));
            }
            let matches = J::Arr(v.targets.iter().map(|t| obj(vec![("node.name", s(t))])).collect());
            (
                None,
                Some(obj(vec![
                    ("name", bare("libpipewire-module-combine-stream")),
                    (
                        "args",
                        obj(vec![
                            ("combine.mode", bare("sink")),
                            ("node.name", s(&v.name)),
                            ("node.description", s(&d)),
                            ("combine.latency-compensate", J::Bool(true)),
                            ("combine.props", obj(vec![("audio.position", positions(v.channels))])),
                            ("stream.rules", J::Arr(vec![obj(vec![("matches", matches), ("actions", obj(vec![("create-stream", obj(vec![]))]))])])),
                        ]),
                    ),
                ])),
            )
        }
        VirtualKind::Loopback => {
            need(&v.source, "source")?;
            need(&v.target, "target")?;
            (
                None,
                Some(obj(vec![
                    ("name", bare("libpipewire-module-loopback")),
                    (
                        "args",
                        obj(vec![
                            ("node.description", s(&d)),
                            ("capture.props", obj(vec![("node.name", s(&format!("{}.capture", v.name))), ("target.object", s(&v.source))])),
                            ("playback.props", obj(vec![("node.name", s(&v.name)), ("target.object", s(&v.target))])),
                        ]),
                    ),
                ])),
            )
        }
        VirtualKind::EchoCancel => {
            let mut capture = vec![("node.name", s(&format!("{}.capture", v.name)))];
            if !v.target.is_empty() {
                capture.push(("target.object", s(&v.target)));
            }
            (
                None,
                Some(obj(vec![
                    ("name", bare("libpipewire-module-echo-cancel")),
                    (
                        "args",
                        obj(vec![
                            ("library.name", bare("aec/libspa-aec-webrtc")),
                            ("monitor.mode", J::Bool(true)),
                            ("capture.props", obj(capture)),
                            ("source.props", obj(vec![("node.name", s(&v.name)), ("node.description", s(&d))])),
                            ("sink.props", obj(vec![("node.name", s(&format!("{}.sink", v.name))), ("node.description", s(&format!("{d} (sink)")))])),
                            ("playback.props", obj(vec![("node.name", s(&format!("{}.playback", v.name)))])),
                        ]),
                    ),
                ])),
            )
        }
        VirtualKind::Noise => {
            let mut capture = vec![("node.name", s(&format!("{}.capture", v.name))), ("node.passive", J::Bool(true)), ("audio.rate", J::Int(48000))];
            if !v.target.is_empty() {
                capture.push(("target.object", s(&v.target)));
            }
            (
                None,
                Some(obj(vec![
                    ("name", bare("libpipewire-module-filter-chain")),
                    (
                        "args",
                        obj(vec![
                            ("node.description", s(&d)),
                            ("media.name", s(&d)),
                            (
                                "filter.graph",
                                obj(vec![(
                                    "nodes",
                                    J::Arr(vec![obj(vec![
                                        ("type", bare("ladspa")),
                                        ("name", bare("rnnoise")),
                                        ("plugin", bare("librnnoise_ladspa")),
                                        ("label", bare("noise_suppressor_mono")),
                                        ("control", obj(vec![("VAD Threshold (%)", J::Float(50.0)), ("VAD Grace Period (ms)", J::Int(200)), ("Retroactive VAD Grace (ms)", J::Int(0))])),
                                    ])]),
                                )]),
                            ),
                            ("capture.props", obj(capture)),
                            ("playback.props", obj(vec![("node.name", s(&v.name)), ("media.class", bare("Audio/Source")), ("audio.rate", J::Int(48000))])),
                        ]),
                    ),
                ])),
            )
        }
        VirtualKind::Equalizer => {
            need(&v.target, "target")?;
            if v.bands.is_empty() {
                return Err(format!("virtual “{}”: add at least one band", v.name));
            }
            let nodes: Vec<J> = v
                .bands
                .iter()
                .enumerate()
                .map(|(i, b)| {
                    obj(vec![
                        ("type", bare("builtin")),
                        ("name", bare(&format!("eq_band_{}", i + 1))),
                        ("label", bare("bq_peaking")),
                        ("control", obj(vec![("Freq", J::Float(b.freq as f64)), ("Q", J::Float(b.q as f64)), ("Gain", J::Float(b.gain as f64))])),
                    ])
                })
                .collect();
            let links: Vec<J> = (1..v.bands.len())
                .map(|i| obj(vec![("output", s(&format!("eq_band_{i}:Out"))), ("input", s(&format!("eq_band_{}:In", i + 1)))]))
                .collect();
            let mut graph = vec![("nodes", J::Arr(nodes))];
            if !links.is_empty() {
                graph.push(("links", J::Arr(links)));
            }
            (
                None,
                Some(obj(vec![
                    ("name", bare("libpipewire-module-filter-chain")),
                    (
                        "args",
                        obj(vec![
                            ("node.description", s(&d)),
                            ("media.name", s(&d)),
                            ("filter.graph", J::Obj(graph.into_iter().map(|(k, v)| (k.to_string(), v)).collect())),
                            ("audio.channels", J::Int(v.channels as i64)),
                            ("audio.position", positions(v.channels)),
                            ("capture.props", obj(vec![("node.name", s(&v.name)), ("media.class", bare("Audio/Sink"))])),
                            ("playback.props", obj(vec![("node.name", s(&format!("{}.output", v.name))), ("node.passive", J::Bool(true)), ("target.object", s(&v.target))])),
                        ]),
                    ),
                ])),
            )
        }
    })
}

fn virtuals(cfg: &Config, errors: &mut Vec<String>) -> Option<String> {
    let mut objects = Vec::new();
    let mut modules = Vec::new();
    let mut seen = BTreeSet::new();
    for v in &cfg.virtuals {
        if v.name.trim().is_empty() || !v.name.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '-' | '.')) {
            errors.push(format!("virtual “{}”: name must be letters, digits, '_', '-' or '.'", v.name));
            continue;
        }
        if !seen.insert(v.name.clone()) {
            errors.push(format!("virtual “{}”: name used twice", v.name));
            continue;
        }
        match virtual_module(v) {
            Ok((o, m)) => {
                objects.extend(o);
                modules.extend(m);
            }
            Err(e) => errors.push(e),
        }
    }
    let mut sections = Vec::new();
    if !objects.is_empty() {
        sections.push(("context.objects", J::Arr(objects)));
    }
    if !modules.is_empty() {
        sections.push(("context.modules", J::Arr(modules)));
    }
    if sections.is_empty() {
        None
    } else {
        Some(render("Virtual devices ([[virtual]]).", sections))
    }
}

/// Everything audio-tui would write, given `cfg`. Problems in the config are
/// returned in `errors` (those entries are skipped).
pub fn generate(cfg: &Config, d: &Dirs) -> (Vec<DropIn>, Vec<String>) {
    let mut errors = Vec::new();
    let files = vec![
        DropIn { path: file(&d.wireplumber, "devices"), content: device_rules(cfg), service: Service::WirePlumber, topic: "device names & priorities" },
        DropIn { path: file(&d.wireplumber, "privacy"), content: privacy_wireplumber(cfg), service: Service::WirePlumber, topic: "privacy" },
        DropIn { path: file(&d.pulse, "rules"), content: client_rules(cfg, "pulse.rules"), service: Service::PipeWirePulse, topic: "per-app rules (Pulse apps)" },
        DropIn { path: file(&d.client, "rules"), content: client_rules(cfg, "stream.rules"), service: Service::Clients, topic: "per-app rules (native apps)" },
        DropIn { path: file(&d.pipewire, "clock"), content: clock(cfg), service: Service::PipeWire, topic: "sample rate & buffer" },
        DropIn { path: file(&d.pipewire, "virtual"), content: virtuals(cfg, &mut errors), service: Service::PipeWire, topic: "virtual devices" },
    ];
    (files, errors)
}

#[derive(Clone, Debug, PartialEq)]
pub enum Change {
    Written,
    Removed,
}

/// Write/remove files that differ from what's on disk.
/// Returns (path, change, service) for each file touched.
pub fn apply(files: &[DropIn]) -> std::io::Result<Vec<(PathBuf, Change, Service)>> {
    let mut changed = Vec::new();
    for f in files {
        let on_disk = std::fs::read_to_string(&f.path).ok();
        match (&f.content, on_disk) {
            (Some(c), Some(d)) if *c == d => {}
            (Some(c), _) => {
                if let Some(dir) = f.path.parent() {
                    std::fs::create_dir_all(dir)?;
                }
                let tmp = f.path.with_extension("conf.tmp");
                std::fs::write(&tmp, c)?;
                std::fs::rename(&tmp, &f.path)?;
                changed.push((f.path.clone(), Change::Written, f.service));
            }
            (None, Some(_)) => {
                std::fs::remove_file(&f.path)?;
                changed.push((f.path.clone(), Change::Removed, f.service));
            }
            (None, None) => {}
        }
    }
    Ok(changed)
}

/// Which files are pending (generated content differs from disk).
pub fn pending(files: &[DropIn]) -> Vec<&DropIn> {
    files.iter().filter(|f| std::fs::read_to_string(&f.path).ok() != f.content).collect()
}


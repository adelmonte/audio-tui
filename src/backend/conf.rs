    #[test]
    fn apply_writes_then_removes() {
        let root = std::env::temp_dir().join(format!("audio-tui-conf-{}", std::process::id()));
        let d = Dirs::under(&root);
        let mut c = cfg();
        c.clock.quantum = 512;
        let (files, _) = generate(&c, &d);
        let ch = apply(&files).unwrap();
        assert_eq!(ch.len(), 1);
        assert_eq!(ch[0].2, Service::PipeWire);
        assert!(pending(&files).is_empty());
        assert!(apply(&files).unwrap().is_empty(), "idempotent");
        let (files, _) = generate(&cfg(), &d);
        let ch = apply(&files).unwrap();
        assert_eq!(ch[0].1, Change::Removed);
        std::fs::remove_dir_all(&root).ok();
    }
